// src/services/storage.service.js
// Where customer documents live. Two drivers, same functions:
//
//   r2    (production)  Phone ──PUT signed URL──► Cloudflare R2 ──GET signed URL──► kiosk / shop computer
//   local (your laptop) Same flow, but the "signed URLs" point at this server
//                       (/api/local-storage) and files sit in LOCAL_STORAGE_DIR.
//
// Set STORAGE_DRIVER in .env (defaults to r2 when R2 keys exist, else local).
const fs = require("fs");
const fsp = require("fs/promises");
const path = require("path");
const crypto = require("crypto");
const env = require("../config/env");

/* ─────────────────────────── R2 driver ─────────────────────────── */
function makeR2Driver() {
  const {
    S3Client, PutObjectCommand, GetObjectCommand, HeadObjectCommand, DeleteObjectCommand,
  } = require("@aws-sdk/client-s3");
  const { getSignedUrl } = require("@aws-sdk/s3-request-presigner");

  if (!env.R2_ENABLED) return null;
  const client = new S3Client({
    region: "auto",
    endpoint: env.R2_ENDPOINT,
    credentials: { accessKeyId: env.R2_ACCESS_KEY_ID, secretAccessKey: env.R2_SECRET_ACCESS_KEY },
    forcePathStyle: env.R2_FORCE_PATH_STYLE,
    // Only send checksums when required — browsers can't send the extra headers.
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  });
  const Bucket = env.R2_BUCKET;

  return {
    name: "r2",
    createUploadUrl: (key, contentType) =>
      getSignedUrl(client, new PutObjectCommand({ Bucket, Key: key, ContentType: contentType }),
        { expiresIn: env.R2_UPLOAD_URL_TTL_SECONDS }),
    createDownloadUrl: (key, fileName) =>
      getSignedUrl(client, new GetObjectCommand({
        Bucket, Key: key, ResponseContentDisposition: `attachment; filename="${safeName(fileName)}"`,
      }), { expiresIn: env.R2_DOWNLOAD_URL_TTL_SECONDS }),
    async getInfo(key) {
      try {
        const r = await client.send(new HeadObjectCommand({ Bucket, Key: key }));
        return { size: r.ContentLength, contentType: r.ContentType };
      } catch (err) {
        if (err.name === "NotFound" || err.$metadata?.httpStatusCode === 404) return null;
        throw err;
      }
    },
    async getBuffer(key) {
      const r = await client.send(new GetObjectCommand({ Bucket, Key: key }));
      return Buffer.from(await r.Body.transformToByteArray());
    },
    putBuffer: (key, buffer, contentType) =>
      client.send(new PutObjectCommand({ Bucket, Key: key, Body: buffer, ContentType: contentType })),
    remove: (key) => client.send(new DeleteObjectCommand({ Bucket, Key: key })),
  };
}

/* ────────────────────────── local driver ────────────────────────── */
// Links are signed with HMAC(JWT_SECRET) and expire like R2's do.
function signLocal(op, key, exp) {
  return crypto.createHmac("sha256", env.JWT_SECRET).update(`${op}\n${key}\n${exp}`).digest("hex");
}

function verifyLocalSignature(op, key, exp, sig) {
  if (!key || !exp || !sig) return false;
  if (Number(exp) < Math.floor(Date.now() / 1000)) return false;
  const expected = Buffer.from(signLocal(op, key, exp));
  const given = Buffer.from(String(sig));
  return expected.length === given.length && crypto.timingSafeEqual(expected, given);
}

function localPath(key) {
  // Keys are generated by us ("jobs/JOB_x/hex.ext"); still refuse anything that escapes the folder.
  const full = path.resolve(env.LOCAL_STORAGE_DIR, key);
  if (!full.startsWith(env.LOCAL_STORAGE_DIR + path.sep)) throw new Error("Bad storage key");
  return full;
}

function makeLocalDriver() {
  fs.mkdirSync(env.LOCAL_STORAGE_DIR, { recursive: true });
  const link = (op, key, ttl, extra = "") => {
    const exp = Math.floor(Date.now() / 1000) + ttl;
    const q = new URLSearchParams({ key, exp: String(exp), sig: signLocal(op, key, exp) });
    return `${env.API_BASE_URL}/local-storage/${op}?${q.toString()}${extra}`;
  };
  return {
    name: "local",
    createUploadUrl: async (key) => link("put", key, env.R2_UPLOAD_URL_TTL_SECONDS),
    createDownloadUrl: async (key, fileName) =>
      link("get", key, env.R2_DOWNLOAD_URL_TTL_SECONDS, `&name=${encodeURIComponent(safeName(fileName))}`),
    async getInfo(key) {
      try {
        const st = await fsp.stat(localPath(key));
        return { size: st.size, contentType: null };
      } catch (err) {
        if (err.code === "ENOENT") return null;
        throw err;
      }
    },
    getBuffer: (key) => fsp.readFile(localPath(key)),
    async putBuffer(key, buffer) {
      const p = localPath(key);
      await fsp.mkdir(path.dirname(p), { recursive: true });
      await fsp.writeFile(p, buffer);
    },
    async remove(key) {
      try {
        await fsp.unlink(localPath(key));
      } catch (err) {
        if (err.code !== "ENOENT") throw err;
      }
    },
  };
}

function safeName(fileName) {
  return String(fileName || "document").replace(/["\\\r\n]/g, "_");
}

const driver = env.STORAGE_DRIVER === "local" ? makeLocalDriver() : makeR2Driver();

function isEnabled() {
  return !!driver;
}

function requireDriver() {
  if (!driver) {
    const err = new Error("File storage is not configured");
    err.status = 503;
    throw err;
  }
  return driver;
}

module.exports = {
  isEnabled,
  driverName: () => (driver ? driver.name : null),
  createUploadUrl: (key, contentType) => requireDriver().createUploadUrl(key, contentType),
  createDownloadUrl: (key, fileName) => requireDriver().createDownloadUrl(key, fileName),
  getInfo: (key) => requireDriver().getInfo(key),
  getBuffer: (key) => requireDriver().getBuffer(key),
  putBuffer: (key, buffer, contentType) => requireDriver().putBuffer(key, buffer, contentType),
  remove: (key) => requireDriver().remove(key),
  // used by routes/localStorage.routes.js
  _local: { verifyLocalSignature, localPath },
};
